#!/usr/bin/env python3
"""
plot_ortholog_validity_qc_summary_v1.py

Summarize ortholog QC results from ortholog_validity.tsv and generate 3 figures:

1. Per-genome stacked bar figure showing the fraction of orthologs in each
   final_qc category.
2. Shared-ortholog counts across genome subsets, comparing:
      - strict shared passing orthologs
      - shared orthologs retained when rescued is also allowed
3. A stacked-bar decomposition showing:
      - shared orthologs that are all passing
      - additional shared orthologs recovered only by allowing rescued

This script is designed for output generated by:
    04b_qualtiy_control_v2.py

Expected input columns:
    accession
    odb12_id
    final_qc
    macse_qc
    raw_cds_qc
    raw_length
    raw_length_mod_3
    raw_internal_stop_count
    raw_terminal_stop
    raw_ambiguous_fraction
    raw_invalid_fraction
    raw_failure_reasons
    macse_frameshift
    macse_internal_stop
    macse_terminal_stop
    macse_failure_reasons
    qc_version

Typical use:
python plot_ortholog_validity_qc_summary_v1.py \
    /Users/rossoaa/projects/genomes/records/compleasm/records/ortholog_validity/body-size-dna-dynamics_manifest/ortholog_validity.tsv \
    --omit-group o5  /path/to/t1.0_e1_o5_i_braminus_dropped_accessions.txt \
    --omit-group o15 /path/to/t1.0_e1_o15_i_braminus_dropped_accessions.txt \
    --omit-group o25 /path/to/t1.0_e1_o25_i_braminus_dropped_accessions.txt \
    --omit-group o35 /path/to/t1.0_e1_o35_i_braminus_dropped_accessions.txt

The full cohort is inferred from the accessions present in ortholog_validity.tsv.
Each omit-group file should contain one accession per line. Blank lines and lines
starting with # are ignored.

Outputs:
    <output_dir>/per_genome_final_qc_fraction.png
    <output_dir>/shared_orthologs_passing_vs_passing_plus_rescued.png
    <output_dir>/shared_orthologs_rescued_gain_stacked.png
    <output_dir>/per_genome_final_qc_summary.tsv
    <output_dir>/cohort_shared_ortholog_summary.tsv
    <output_dir>/cohort_membership_summary.tsv
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

import matplotlib.pyplot as plt
import pandas as pd


FINAL_QC_ORDER = [
    "passing",
    "rescued",
    "alignment-problematic",
    "unsuitable",
]

FIG1_WIDTH = 12
FIG1_MIN_HEIGHT = 10
FIG1_ROW_HEIGHT = 0.28

FIG2_WIDTH = 8
FIG2_HEIGHT = 6

FIG3_WIDTH = 8
FIG3_HEIGHT = 6

DPI = 300
AXES_LINEWIDTH = 1.5
FONT_SIZE = 11
TITLE_SIZE = 13
LEGEND_SIZE = 10
TICK_LABEL_SIZE = 9


def load_omit_file(path: Path) -> List[str]:
    values = []
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            value = line.strip()
            if not value or value.startswith("#"):
                continue
            values.append(value.split()[0])
    return sorted(set(values))


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Summarize ortholog QC results and generate figures for per-genome "
            "QC distributions and shared ortholog counts across omit-genome cohorts."
        ),
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "ortholog_validity_tsv",
        help="Path to ortholog_validity.tsv from 04b_qualtiy_control_v2.py",
    )
    parser.add_argument(
        "--omit-group",
        nargs=2,
        action="append",
        metavar=("LABEL", "FILE"),
        default=[],
        help=(
            "Add one omit-genome group, e.g. --omit-group o5 dropped_accessions.txt. "
            "May be supplied multiple times."
        ),
    )
    parser.add_argument(
        "--output-dir",
        default=None,
        help=(
            "Output directory for figures and summary TSVs. "
            "Default: <ortholog_validity.tsv parent>/qc_summary_figures"
        ),
    )
    return parser.parse_args()


def validate_input_table(df: pd.DataFrame) -> None:
    required = {
        "accession",
        "odb12_id",
        "final_qc",
        "macse_qc",
        "raw_cds_qc",
    }
    missing = required.difference(df.columns)
    if missing:
        raise ValueError(
            f"ortholog_validity.tsv is missing required columns: {sorted(missing)}"
        )

    duplicates = df.duplicated(subset=["accession", "odb12_id"])
    if duplicates.any():
        dup_rows = df.loc[duplicates, ["accession", "odb12_id"]]
        preview = dup_rows.head(10).to_dict("records")
        raise ValueError(
            "Input table contains duplicate accession + odb12_id combinations. "
            f"First duplicates: {preview}"
        )

    bad_categories = sorted(set(df["final_qc"]) - set(FINAL_QC_ORDER))
    if bad_categories:
        raise ValueError(
            "Input table contains unexpected final_qc values: "
            f"{bad_categories}"
        )


def make_output_dir(tsv_path: Path, user_output_dir: str | None) -> Path:
    if user_output_dir:
        outdir = Path(user_output_dir).expanduser().resolve()
    else:
        outdir = tsv_path.resolve().parent / "qc_summary_figures"
    outdir.mkdir(parents=True, exist_ok=True)
    return outdir


def build_cohorts(
    all_accessions: Sequence[str],
    omit_groups: Sequence[Tuple[str, Path]],
) -> Tuple[List[Dict[str, object]], pd.DataFrame]:
    full_set = set(all_accessions)
    cohorts: List[Dict[str, object]] = []
    membership_rows: List[Dict[str, object]] = []

    cohorts.append(
        {
            "cohort_label": "all_85",
            "display_label": f"{len(full_set)} genomes (all)",
            "subset_size": len(full_set),
            "excluded_count": 0,
            "accessions": full_set,
            "source_file": "all genomes in ortholog_validity.tsv",
        }
    )
    for accession in sorted(full_set):
        membership_rows.append(
            {
                "cohort_label": "all_85",
                "display_label": f"{len(full_set)} genomes (all)",
                "accession": accession,
                "included": True,
                "source_file": "all genomes in ortholog_validity.tsv",
            }
        )

    for label, file_path in omit_groups:
        omitted = set(load_omit_file(file_path))
        unknown = sorted(omitted.difference(full_set))
        if unknown:
            print(
                f"Warning: {len(unknown)} accession(s) in {file_path} were not found "
                f"in ortholog_validity.tsv and will be ignored."
            )

        omitted_in_full = omitted.intersection(full_set)
        retained = full_set.difference(omitted_in_full)
        display_label = f"{len(retained)} genomes ({label})"

        cohorts.append(
            {
                "cohort_label": label,
                "display_label": display_label,
                "subset_size": len(retained),
                "excluded_count": len(omitted_in_full),
                "accessions": retained,
                "source_file": str(file_path),
            }
        )

        for accession in sorted(full_set):
            membership_rows.append(
                {
                    "cohort_label": label,
                    "display_label": display_label,
                    "accession": accession,
                    "included": accession in retained,
                    "source_file": str(file_path),
                }
            )

    membership_df = pd.DataFrame(membership_rows)
    return cohorts, membership_df


def summarize_per_genome(df: pd.DataFrame) -> pd.DataFrame:
    counts = (
        df.groupby(["accession", "final_qc"])
        .size()
        .unstack(fill_value=0)
        .reindex(columns=FINAL_QC_ORDER, fill_value=0)
    )

    counts["total_ortholog_rows"] = counts.sum(axis=1)

    for qc in FINAL_QC_ORDER:
        counts[f"{qc}_fraction"] = counts[qc] / counts["total_ortholog_rows"]

    counts["passing_plus_rescued"] = counts["passing"] + counts["rescued"]
    counts["passing_plus_rescued_fraction"] = (
        counts["passing_plus_rescued"] / counts["total_ortholog_rows"]
    )

    counts = counts.sort_values(
        by=["passing_plus_rescued_fraction", "passing_fraction", "rescued_fraction"],
        ascending=[False, False, False],
    )
    counts = counts.reset_index()
    return counts


def summarize_cohort_shared_orthologs(
    df: pd.DataFrame,
    cohorts: Sequence[Dict[str, object]],
) -> pd.DataFrame:
    records = []

    for cohort in cohorts:
        accession_set = set(cohort["accessions"])
        cohort_df = df[df["accession"].isin(accession_set)].copy()
        subset_size = int(cohort["subset_size"])

        by_ortholog = cohort_df.groupby("odb12_id")

        shared_full = 0
        shared_passing = 0
        shared_passing_or_rescued = 0
        orthologs_considered = cohort_df["odb12_id"].nunique()

        for _, group in by_ortholog:
            if group["accession"].nunique() != subset_size:
                continue
            if len(group) != subset_size:
                continue

            shared_full += 1

            qc_set = set(group["final_qc"].astype(str))
            if qc_set.issubset({"passing"}):
                shared_passing += 1

            if qc_set.issubset({"passing", "rescued"}):
                shared_passing_or_rescued += 1

        rescued_gain = shared_passing_or_rescued - shared_passing

        records.append(
            {
                "cohort_label": cohort["cohort_label"],
                "display_label": cohort["display_label"],
                "subset_size": subset_size,
                "excluded_count": cohort["excluded_count"],
                "orthologs_observed_in_subset": orthologs_considered,
                "shared_full_representation": shared_full,
                "shared_strict_passing": shared_passing,
                "shared_passing_or_rescued": shared_passing_or_rescued,
                "rescued_gain": rescued_gain,
                "rescued_gain_fraction_of_passresc": (
                    rescued_gain / shared_passing_or_rescued
                    if shared_passing_or_rescued > 0
                    else 0.0
                ),
            }
        )

    summary_df = pd.DataFrame(records)
    summary_df = summary_df.sort_values("subset_size", ascending=False).reset_index(drop=True)
    return summary_df


def clean_axes(ax) -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_linewidth(AXES_LINEWIDTH)
    ax.tick_params(axis="both", labelsize=TICK_LABEL_SIZE)


def plot_per_genome(per_genome: pd.DataFrame, output_path: Path) -> None:
    n = len(per_genome)
    fig_height = max(FIG1_MIN_HEIGHT, n * FIG1_ROW_HEIGHT)

    fig, ax = plt.subplots(figsize=(FIG1_WIDTH, fig_height))

    y = list(range(n))
    left = [0.0] * n

    for qc in FINAL_QC_ORDER:
        values = per_genome[f"{qc}_fraction"].tolist()
        ax.barh(y, values, left=left, label=qc)
        left = [l + v for l, v in zip(left, values)]

    ax.set_yticks(y)
    ax.set_yticklabels(per_genome["accession"].tolist(), fontsize=TICK_LABEL_SIZE)
    ax.invert_yaxis()
    ax.set_xlabel("Fraction of evaluated orthologs", fontsize=FONT_SIZE)
    ax.set_ylabel("Genome accession", fontsize=FONT_SIZE)
    ax.set_title("Per-genome final QC composition", fontsize=TITLE_SIZE)
    ax.set_xlim(0, 1.0)

    for yi, total in zip(y, per_genome["total_ortholog_rows"].tolist()):
        ax.text(
            1.005,
            yi,
            f"n={total}",
            va="center",
            ha="left",
            fontsize=8,
            clip_on=False,
        )

    clean_axes(ax)
    ax.legend(
        title="final_qc",
        frameon=False,
        fontsize=LEGEND_SIZE,
        title_fontsize=LEGEND_SIZE,
        loc="lower right",
    )

    plt.tight_layout()
    fig.savefig(output_path, dpi=DPI, bbox_inches="tight")
    plt.close(fig)


def plot_shared_passing_vs_rescued(cohort_summary: pd.DataFrame, output_path: Path) -> None:
    plot_df = cohort_summary.sort_values("subset_size")
    x = list(range(len(plot_df)))
    width = 0.36

    strict = plot_df["shared_strict_passing"].tolist()
    passresc = plot_df["shared_passing_or_rescued"].tolist()
    rescued_gain = plot_df["rescued_gain"].tolist()
    labels = plot_df["display_label"].tolist()

    fig, ax = plt.subplots(figsize=(FIG2_WIDTH, FIG2_HEIGHT))
    bars1 = ax.bar([i - width / 2 for i in x], strict, width=width, label="all passing")
    bars2 = ax.bar([i + width / 2 for i in x], passresc, width=width, label="passing + rescued")

    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=30, ha="right")
    ax.set_ylabel("Number of shared orthologs", fontsize=FONT_SIZE)
    ax.set_xlabel("Genome subset", fontsize=FONT_SIZE)
    ax.set_title(
        "Shared orthologs under strict passing vs passing + rescued",
        fontsize=TITLE_SIZE,
    )

    for bar2, gain in zip(bars2, rescued_gain):
        ax.text(
            bar2.get_x() + bar2.get_width() / 2,
            bar2.get_height(),
            f"+{gain}",
            ha="center",
            va="bottom",
            fontsize=9,
        )

    clean_axes(ax)
    ax.legend(frameon=False, fontsize=LEGEND_SIZE, loc="best")

    plt.tight_layout()
    fig.savefig(output_path, dpi=DPI, bbox_inches="tight")
    plt.close(fig)


def plot_rescued_gain_stacked(cohort_summary: pd.DataFrame, output_path: Path) -> None:
    plot_df = cohort_summary.sort_values("subset_size")
    x = list(range(len(plot_df)))
    strict = plot_df["shared_strict_passing"].tolist()
    gain = plot_df["rescued_gain"].tolist()
    labels = plot_df["display_label"].tolist()

    fig, ax = plt.subplots(figsize=(FIG3_WIDTH, FIG3_HEIGHT))
    ax.bar(x, strict, label="all passing")
    ax.bar(x, gain, bottom=strict, label="additional shared orthologs gained by rescued")

    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=30, ha="right")
    ax.set_ylabel("Number of shared orthologs", fontsize=FONT_SIZE)
    ax.set_xlabel("Genome subset", fontsize=FONT_SIZE)
    ax.set_title("Contribution of rescued orthologs to shared-ortholog recovery", fontsize=TITLE_SIZE)

    totals = [a + b for a, b in zip(strict, gain)]
    for xi, total, add in zip(x, totals, gain):
        ax.text(
            xi,
            total,
            f"{total}\n(+{add})",
            ha="center",
            va="bottom",
            fontsize=9,
        )

    clean_axes(ax)
    ax.legend(frameon=False, fontsize=LEGEND_SIZE, loc="best")

    plt.tight_layout()
    fig.savefig(output_path, dpi=DPI, bbox_inches="tight")
    plt.close(fig)


def print_console_summary(
    per_genome: pd.DataFrame,
    cohort_summary: pd.DataFrame,
    outdir: Path,
) -> None:
    print("\nSUMMARY")
    print("-" * 80)
    print(f"Genomes in table: {per_genome.shape[0]}")
    print(
        f"Median ortholog rows per genome: "
        f"{per_genome['total_ortholog_rows'].median():.0f}"
    )
    print("\nTop 10 genomes by passing+rescued fraction:")
    top_cols = [
        "accession",
        "total_ortholog_rows",
        "passing_fraction",
        "rescued_fraction",
        "passing_plus_rescued_fraction",
    ]
    print(per_genome[top_cols].head(10).to_string(index=False))

    print("\nCohort shared-ortholog summary:")
    print(
        cohort_summary[
            [
                "display_label",
                "subset_size",
                "shared_full_representation",
                "shared_strict_passing",
                "shared_passing_or_rescued",
                "rescued_gain",
            ]
        ].to_string(index=False)
    )

    print(f"\nOutput directory: {outdir}")


def main() -> None:
    args = parse_args()

    tsv_path = Path(args.ortholog_validity_tsv).expanduser().resolve()
    if not tsv_path.exists():
        raise FileNotFoundError(f"ortholog_validity.tsv not found: {tsv_path}")

    omit_groups = []
    for label, file_str in args.omit_group:
        file_path = Path(file_str).expanduser().resolve()
        if not file_path.exists():
            raise FileNotFoundError(f"Omit-group file not found: {file_path}")
        omit_groups.append((label, file_path))

    outdir = make_output_dir(tsv_path, args.output_dir)

    print(f"Reading: {tsv_path}")
    df = pd.read_csv(tsv_path, sep="\t", dtype={"accession": str, "odb12_id": str})
    validate_input_table(df)

    df["final_qc"] = pd.Categorical(df["final_qc"], categories=FINAL_QC_ORDER, ordered=True)

    all_accessions = sorted(df["accession"].unique())
    all_orthologs = df["odb12_id"].nunique()

    print(f"Rows loaded:      {len(df)}")
    print(f"Accessions:       {len(all_accessions)}")
    print(f"Ortholog IDs:     {all_orthologs}")

    cohorts, membership_df = build_cohorts(all_accessions, omit_groups)
    per_genome = summarize_per_genome(df)
    cohort_summary = summarize_cohort_shared_orthologs(df, cohorts)

    per_genome_out = outdir / "per_genome_final_qc_summary.tsv"
    cohort_out = outdir / "cohort_shared_ortholog_summary.tsv"
    membership_out = outdir / "cohort_membership_summary.tsv"

    per_genome.to_csv(per_genome_out, sep="\t", index=False)
    cohort_summary.to_csv(cohort_out, sep="\t", index=False)
    membership_df.to_csv(membership_out, sep="\t", index=False)

    fig1 = outdir / "per_genome_final_qc_fraction.png"
    fig2 = outdir / "shared_orthologs_passing_vs_passing_plus_rescued.png"
    fig3 = outdir / "shared_orthologs_rescued_gain_stacked.png"

    plot_per_genome(per_genome, fig1)
    plot_shared_passing_vs_rescued(cohort_summary, fig2)
    plot_rescued_gain_stacked(cohort_summary, fig3)

    print_console_summary(per_genome, cohort_summary, outdir)

    print("\nWROTE FILES")
    print("-" * 80)
    for path in [per_genome_out, cohort_out, membership_out, fig1, fig2, fig3]:
        print(path)


if __name__ == "__main__":
    main()
